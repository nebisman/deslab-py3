def iscontrollable(H, G):
    """
    This function tests if the language generated by H is
    controllable with respect to G and the uncontrollable events
    of G (G.Sigma - G.Sigcon), i.e. if L(H)Sigma_uc & L(G) <= L(H).
    """
    Sigma_uc = G.Sigma - G.Sigcon
    H0 = product(H, G)
    for (y, x) in H0.X:
        G_events_uc = G.Gamma(x) & Sigma_uc
        if not H0.Gamma((y, x)) >= G_events_uc:
            return False
    return True


def is2controllable(H, G):
    """
    Controllability test of pre(Lm(H)) with respect to pre(Lm(G)):
    H is augmented with a marked dump state reached through the
    uncontrollable events not enabled in H.
    """
    Sigma_uc = G.Sigma - G.Sigcon
    G_pc = pclosure(G)
    H_pc = pclosure(H)
    dump = _newstate(H_pc.X, 'D')
    Haug = H_pc.addstate(dump, marked=True)
    for state in H_pc.X:
        for event in (Sigma_uc - H_pc.Gamma(state)):
            Haug = Haug.addtransition([state, event, dump])
    L = Haug & G_pc
    return L <= H_pc


def supcontrollable(H, G, verbose=False):
    """
    This function calculates an automaton that marks the supremal
    controllable sublanguage of Lm(H) with respect to G and the set
    of uncontrollable events G.Sigma - G.Sigcon. If Lm(H) is prefix
    closed the algorithm based on language operations is used,
    otherwise the general iterative algorithm.
    """
    if ispfclosed(H):
        if verbose:
            print('Using Prefix Closed Algorithm')
        Ksupc = supcontrollablepfclosed(H, G)
    else:
        if verbose:
            print('Using General Algorithm')
        Ksupc = supcontrollablegeneral(H, G)
    if not Ksupc.empty:
        Ksupc = Ksupc.renamestates('number')
    Ksupc = Ksupc.setpar(name=r'$K^{\uparrow C}$')
    return Ksupc


def supcontrollablegeneral(H, G):
    """
    General algorithm for the supremal controllable sublanguage:
    the states (y,x) of H x G in which some uncontrollable event
    feasible in G is not enabled are deleted until a fixed point
    is reached (the result is trimmed in each iteration).
    """
    Sigma_uc = G.Sigma - G.Sigcon
    H0 = H & G.setpar(Xm=G.X)
    H0_changed = True
    while H0_changed and not H0.empty:
        H0_changed = False
        for (y, x) in _sorted(H0.X):
            if H0.empty:
                break
            G_events_uc = G.Gamma(x) & Sigma_uc
            if not (G_events_uc <= H0.Gamma((y, x))):
                H0 = H0.deletestate((y, x))
                H0_changed = True
        H0 = trim(H0)
    return H0


def supcontrollablepfclosed(H, G):
    """
    Supremal controllable sublanguage of a prefix closed
    language: K - ((L - K)/Sigma_uc^*)Sigma^*
    """
    E_clos = sigmakleeneclos(G.Sigma)
    Sigma_uc = G.Sigma - G.Sigcon
    E_uc_clos = sigmakleeneclos(Sigma_uc)
    Ksupc = H - (((G - H) / E_uc_clos) * E_clos)
    return Ksupc
