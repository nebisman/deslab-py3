def allevents(G):
    """
    This function returns a single state automaton with a self
    loop for each event of G. Its single state is initial and
    marked, so it generates and marks Sigma^*, where Sigma is the
    set of events of G. The observable and controllable events
    and the LaTeX labels of the events of G are preserved.

    Example
    -------
    syms('x0 x1 a u')
    G = fsa([x0, x1], [a, u], [(x0, a, x1), (x1, u, x0)], [x0], [x0], Sigcon=[a])
    E = allevents(G)
    draw(E)
    """
    x0 = 0
    Sigma = G.Sigma 
    transitions = [(x0, e, x0) for e in _sorted(Sigma)]
    table =  [(e, G.symDict[e]) for e in _sorted(Sigma) if e in G.symDict]
    return fsa([x0], Sigma, transitions, [x0], [x0], table,
               Sigobs=G.Sigobs & Sigma, Sigcon=G.Sigcon & Sigma, name=r'$\Sigma^*$')


def unconselfloops(A):
    """
    This function returns a copy of the automaton A, usually a
    specification, with a self loop at each state x for each
    uncontrollable event of A (A.Sigma - A.Sigcon) that is not
    active at x, i.e. that is not in A.Gamma(x). The transitions,
    marked states, controllable and observable events, LaTeX labels
    and name of A are preserved, and A remains deterministic if it
    was.

    A specification that does not accept an uncontrollable event at
    a state asks the supervisor to prevent that event, which it can
    only do by disabling controllable events earlier. With the self
    loops the specification never blocks an uncontrollable event: it
    only restricts the controllable ones, and an uncontrollable event
    that was not active does not change its state.

    Example
    -------
    syms('B0 B1 t1 r e2')
    E1 = fsa([B0, B1], [t1, r, e2], [(B0, t1, B1), (B0, r, B1), (B1, e2, B0)],
             [B0], [B0], Sigcon=[e2], name='$E_1$')
    E1u = unconselfloops(E1)   # adds (B1, t1, B1) and (B1, r, B1)
    draw(E1, E1u)
    """
    auto = A.copy()
    if A.empty:
        return auto
    uncontrollable = A.Sigma - A.Sigcon - EMPTYSTRINGSET
    for state in A.X:
        for event in _sorted(uncontrollable - A.Gamma(state)):
            auto.Graph.add_edge(state, state, key=event, label=event)
    auto._rebuild()
    return auto


def nonconflict(G1, G2):
    """
    This function tests if the automata G1 and G2 are nonconflicting,
    as the function nonconflict of TCT: it returns True if every
    reachable state of the parallel composition G1 || G2 can reach a
    marked state. When G1 and G2 are trim and have the same events this
    is the condition pre(Lm(G1)) & pre(Lm(G2)) = pre(Lm(G1) & Lm(G2)).
    With G2 = allevents(G1) it tests if G1 is nonblocking.

    Example
    -------
    syms('x0 x1 x2 a b')
    G1 = fsa([x0, x1, x2], [a, b], [(x0, a, x1), (x1, b, x2)], [x0], [x2])
    G2 = fsa([x0, x1, x2], [a, b], [(x0, b, x1), (x1, a, x2)], [x0], [x2])
    print(nonconflict(G1, G2))   # False: G1 marks ab and G2 marks ba
    """
    P = parallel(G1, G2)
    if P.empty:
        return True
    P = ac(P)
    return P.X == coac(P).X


def iscontrollable(H, G):
    """
    This function tests if the language generated by H is
    controllable with respect to G and the uncontrollable events
    of G (G.Sigma - G.Sigcon), i.e. if L(H)Sigma_uc & L(G) <= L(H).
    """
    Sigma_uc = G.Sigma - G.Sigcon
    H0 = product(H, G)
    for (y, x) in H0.X:
        G_events_uc = G.Gamma(x) & Sigma_uc
        if not H0.Gamma((y, x)) >= G_events_uc:
            return False
    return True


def is2controllable(H, G):
    """
    Controllability test of pre(Lm(H)) with respect to pre(Lm(G)):
    H is augmented with a marked dump state reached through the
    uncontrollable events not enabled in H.
    """
    Sigma_uc = G.Sigma - G.Sigcon
    G_pc = pclosure(G)
    H_pc = pclosure(H)
    dump = _newstate(H_pc.X, 'D')
    Haug = H_pc.addstate(dump, marked=True)
    for state in H_pc.X:
        for event in (Sigma_uc - H_pc.Gamma(state)):
            Haug = Haug.addtransition([state, event, dump])
    L = Haug & G_pc
    return L <= H_pc


def supcontrollable(H, G, verbose=False, renamestates=False):
    """
    This function calculates an automaton that marks the supremal
    controllable sublanguage of Lm(H) with respect to G and the set
    of uncontrollable events G.Sigma - G.Sigcon. If Lm(H) is prefix
    closed the algorithm based on language operations is used,
    otherwise the general iterative algorithm.
    """
    # the language algorithm works with the language that H generates; trim H so that it
    # generates Lm(H). If Lm(H) is empty the general algorithm returns the empty supervisor
    Ht = trim(H) if ispfclosed(H) else None
    if Ht is not None and not Ht.empty:
        if verbose:
            print('Using Prefix Closed Algorithm')
        Ksupc = supcontrollablepfclosed(Ht, G)
    else:
        if verbose:
            print('Using General Algorithm')
        Ksupc = supcontrollablegeneral(H, G)
    if not Ksupc.empty:
        if renamestates:
            Ksupc = Ksupc.renamestates('number')
        else:
            Ksupc = _states_of_specification(Ksupc, H)
    Ksupc = Ksupc.setpar(name=r'$K^{\uparrow C}$')
    return Ksupc


def _states_of_specification(K, H):
    """
    Names each state (h, x) of K, built as a product with H, by the
    state h of H, when no two states of K have the same h. K keeps its
    names when it is not such a product (for instance when no state of
    H was removed) or when two of its states share the state of H.
    """
    names = {}
    for state in K.X:
        if not (isinstance(state, tuple) and len(state) == 2 and state[0] in H.X):
            return K
        names[state] = state[0]
    if len(set(names.values())) != len(names):
        return K
    return K.renamestates(names)


def supcontrollablegeneral(H, G):
    """
    General algorithm for the supremal controllable sublanguage:
    the states (y,x) of H x G in which some uncontrollable event
    feasible in G is not enabled are deleted until a fixed point
    is reached (the result is trimmed in each iteration).
    """
    Sigma_uc = G.Sigma - G.Sigcon
    H0 = H & G.setpar(Xm=G.X)
    H0_changed = True
    while H0_changed and not H0.empty:
        H0_changed = False
        for (y, x) in _sorted(H0.X):
            if H0.empty:
                break
            G_events_uc = G.Gamma(x) & Sigma_uc
            if not (G_events_uc <= H0.Gamma((y, x))):
                H0 = H0.deletestate((y, x))
                H0_changed = True
        # the states deleted by trim may create new violations of
        # controllability, so they also require a new iteration
        trimmed = trim(H0)
        if len(trimmed) != len(H0):
            H0_changed = True
        H0 = trimmed
    return H0


def supcontrollablepfclosed(H, G):
    """
    Supremal controllable sublanguage of a prefix closed
    language: K - ((L - K)/Sigma_uc^*)Sigma^*, where L = L(G) is the
    language generated by G, not the marked one
    """
    E_clos = sigmakleeneclos(G.Sigma)
    Sigma_uc = G.Sigma - G.Sigcon
    E_uc_clos = sigmakleeneclos(Sigma_uc)
    L = G.setpar(Xm=G.X)
    Ksupc = H - (((L - H) / E_uc_clos) * E_clos)
    # Sigma* makes every event controllable; keep the classification of H and G,
    # as the general algorithm does with H & G
    return Ksupc.setpar(Sigcon=set((H.Sigcon | G.Sigcon) & Ksupc.Sigma))


def supreduce(S, G):
    """
    This function computes a reduced supervisor for the supervisor S
    and the plant G, as the function supreduce of TCT (Su and Wonham,
    Supervisor reduction for discrete-event systems, 2004). The
    reduced supervisor R is control equivalent to S: R || G generates
    and marks the same strings as S || G, so R enforces the same
    closed-loop behavior with fewer states. R does not track the plant,
    only the information needed to decide which events to disable.

    Two states x and y of S can share a state of R when they are
    control consistent:
      - no event enabled at x is disabled at y, and vice versa; an
        event of S and G is disabled at x if G can execute it after a
        string that reaches x but S does not enable it at x;
      - if x and y are both reached by strings that G marks, or
        neither is, then both are marked in S or both are unmarked.
    The states of S are visited in breadth-first order and each pair
    (x, y) is merged, together with the successors that the merge
    requires to keep R deterministic, when all the merged states are
    pairwise control consistent. Like the algorithm of TCT this is a
    greedy procedure: it gives a small supervisor, not necessarily one
    with the minimum number of states.

    S and G must be deterministic, with one initial state. The states
    of R are numbered 0, 1, 2, ..., and 0 is the initial state. R keeps
    the events of S and their controllability and observability.

    Example
    -------
    syms('a1 b1 a2 b2')
    M1 = fsa([0, 1], [a1, b1], [(0, a1, 1), (1, b1, 0)], [0], [0], Sigcon=[a1])
    M2 = fsa([0, 1], [a2, b2], [(0, a2, 1), (1, b2, 0)], [0], [0], Sigcon=[a2])
    B = fsa([0, 1], [b1, a2], [(0, b1, 1), (1, a2, 0)], [0], [0, 1], Sigcon=[a2])
    G = M1 // M2
    S = supcontrollable(G // B, G)     # 6 states
    R = supreduce(S, G)                # 2 states: the buffer is empty or full
    draw(S, R)
    """
    for name, A in (('S', S), ('G', G)):
        if A.empty or len(A.X0) != 1 or not A.is_dfa() or A.has_epsilon():
            raise ValueError(name + ' must be a nonempty deterministic automaton '
                             'with one initial state')
    order = _breadth_first_states(S)
    table = [(e, S.symDict[e]) for e in _sorted(S.Sigma) if e in S.symDict]
    return _reduced_supervisor(S, G, order, S.Sigcon & S.Sigma, table, r'$S_{red}$')


def _breadth_first_states(S):
    """reachable states of the deterministic automaton S in breadth-first order"""
    initial = next(iter(S.X0))
    order, seen = [initial], {initial}
    for state in order:
        for event in _sorted(S.Gamma(state)):
            target = S.delta(state, event)
            if target not in seen:
                seen.add(target)
                order.append(target)
    return order


def _control_data(S, G):
    """
    Events disabled at each state of S and states of S reached by
    strings marked by G, over the reachable pairs of S || G.
    """
    shared = S.Sigma & G.Sigma
    disabled = {state: set() for state in S.X}
    plant_marked = set()
    start = (next(iter(S.X0)), next(iter(G.X0)))
    seen, pending = {start}, [start]
    while pending:
        x, q = pending.pop()
        enabled, feasible = S.Gamma(x), G.Gamma(q)
        disabled[x] |= (feasible & shared) - enabled
        if q in G.Xm:
            plant_marked.add(x)
        steps = [(S.delta(x, e), G.delta(q, e)) for e in enabled & feasible]
        steps += [(S.delta(x, e), q) for e in enabled - G.Sigma]
        steps += [(x, G.delta(q, e)) for e in feasible - S.Sigma]
        for pair in steps:
            if pair not in seen:
                seen.add(pair)
                pending.append(pair)
    return disabled, plant_marked


def _reduced_supervisor(S, G, order, Sigcon, table=(), name=''):
    """
    Reduced supervisor of S for G: the states of S, listed in order
    (initial state first), are merged greedily into a control
    congruence and numbered by the first state of each cell.
    """
    disabled, plant_marked = _control_data(S, G)
    numbering, transitions, marked = _control_cover(S, order, disabled, plant_marked)
    return fsa(list(range(len(set(numbering.values())))), S.Sigma, transitions, [0], marked,
               list(table), Sigobs=S.Sigobs & S.Sigma, Sigcon=set(Sigcon), name=name)


def _control_cover(S, order, disabled, plant_marked):
    """
    Greedy control congruence of S: the states of S, listed in order
    (initial state first), are merged when they are control consistent
    for the events in disabled. Returns the number of the cell of each
    state, numbered by its first state in order, and the transitions and
    marked states between cells.
    """
    cell = {state: frozenset([state]) for state in order}
    for index, left in enumerate(order):
        for right in order[index + 1:]:
            if cell[left] != cell[right]:
                merged = _merge_control_cells(S, cell, disabled, plant_marked, left, right)
                if merged is not None:
                    cell = merged
    numbers = {c: k for k, c in enumerate(dict.fromkeys(cell[state] for state in order))}
    numbering = {state: numbers[cell[state]] for state in order}
    transitions = {(numbering[x], e, numbering[S.delta(x, e)]) for x in order for e in S.Gamma(x)}
    marked = {numbering[x] for x in S.Xm if x in numbering}
    return numbering, transitions, marked


def localize(S, G, agents):
    """
    This function computes a local controller for each agent of the
    plant G, as the function localize of TCT (Cai and Wonham,
    Supervisor localization: a top-down approach to distributed
    control of discrete-event systems, 2010). S is a supervisor for G,
    usually the monolithic one, and agents are the components of G
    whose controllable events are to be controlled locally, for example
    the machines of a factory. The controllable events of different
    agents must be different.

    The local controller LOC_k of the agent k only enables and disables
    the controllable events of that agent. It is a reduced supervisor,
    computed like supreduce, in which two states of S can share a state
    when they are control consistent for those events only. LOC_k also
    observes the events of the other agents that it needs to decide what
    to disable: these are the communication events between agents.

    The local controllers together are control equivalent to S: the
    composition G || LOC_1 || ... || LOC_n generates and marks the same
    strings as S || G. The list returned has one controller per agent,
    in the same order. The states of each controller are numbered 0, 1,
    2, ..., and 0 is the initial state. As in TCT, each controller keeps
    only the events that change its state and the controllable events of
    its agent that it disables at some state; the other events can
    always occur, without changing its state.

    S and G must be deterministic, with one initial state.

    Example
    -------
    syms('a1 b1 a2 b2')
    M1 = fsa([0, 1], [a1, b1], [(0, a1, 1), (1, b1, 0)], [0], [0], Sigcon=[a1])
    M2 = fsa([0, 1], [a2, b2], [(0, a2, 1), (1, b2, 0)], [0], [0], Sigcon=[a2])
    B = fsa([0, 1], [b1, a2], [(0, b1, 1), (1, a2, 0)], [0], [0, 1], Sigcon=[a2])
    G = M1 // M2
    S = supcontrollable(G // B, G)     # 6 states
    LOC1, LOC2 = localize(S, G, [M1, M2])
    draw(LOC1, LOC2)   # M1 starts when the buffer is empty, M2 when it is full
    """
    for name, A in (('S', S), ('G', G)):
        if A.empty or len(A.X0) != 1 or not A.is_dfa() or A.has_epsilon():
            raise ValueError(name + ' must be a nonempty deterministic automaton '
                             'with one initial state')
    agents = list(agents)
    if not agents:
        raise ValueError('localize needs at least one agent')
    controlled = [A.Sigma & G.Sigcon for A in agents]
    shared = {event for k, mine in enumerate(controlled) for other in controlled[k + 1:]
              for event in mine & other}
    if shared:
        raise ValueError('The controllable events of the agents must be different; shared: '
                         + ', '.join(sorted(map(str, shared))))
    disabled, plant_marked = _control_data(S, G)
    missing = set().union(*disabled.values()) - set().union(*controlled)
    if missing:
        raise ValueError('S disables events of no agent: ' + ', '.join(sorted(map(str, missing))))
    order = _breadth_first_states(S)
    controllers = []
    for k, (A, mine) in enumerate(zip(agents, controlled)):
        own = {state: events & mine for state, events in disabled.items()}
        numbering, transitions, marked = _control_cover(S, order, own, plant_marked)
        states = sorted(set(numbering.values()))
        # the events that change the state, and the events of the agent disabled at some state;
        # where a controller lacks another event, G cannot execute it, so it becomes a self-loop
        kept = {e for x, e, y in transitions if x != y}
        kept |= set().union(*own.values())
        transitions = [(x, e, y) for x, e, y in transitions if e in kept]
        table = [(e, S.symDict[e]) for e in _sorted(kept) if e in S.symDict]
        label = A.name if A.name and A.name != 'untitled' else str(k + 1)
        controllers.append(fsa(states, kept, transitions, [0], marked, table,
                               Sigobs=S.Sigobs & kept, Sigcon=(S.Sigcon | G.Sigcon) & kept,
                               name='LOC ' + label))
    return controllers


def _merge_control_cells(S, cell, disabled, plant_marked, left, right):
    """
    Merge the cells of left and right, and then the cells of their
    successors under each event; None if two merged states are not
    control consistent.
    """
    candidate = cell.copy()
    pending = [(left, right)]
    while pending:
        left, right = pending.pop()
        left_cell, right_cell = candidate[left], candidate[right]
        if left_cell == right_cell:
            continue
        for x in left_cell:
            for y in right_cell:
                if (S.Gamma(x) & disabled[y] or S.Gamma(y) & disabled[x]
                        or ((x in plant_marked) == (y in plant_marked)
                            and (x in S.Xm) != (y in S.Xm))):
                    return None
        merged = left_cell | right_cell
        targets = {}
        for state in merged:
            candidate[state] = merged
            for event in S.Gamma(state):
                target = S.delta(state, event)
                previous = targets.setdefault(event, target)
                if candidate[target] != candidate[previous]:
                    pending.append((target, previous))
    return candidate
